TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{symbol}" (Apache License 2.0), generated by tools/material_symbols.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="{path}" />
    </group>
</vector>
"""


def fetch(symbol: str, filled: bool) -> str:
    style = "fill1" if filled else "default"
    url = f"https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{symbol}/{style}/24px.svg"
    with urllib.request.urlopen(url, timeout=30) as r:
        svg = r.read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if not paths:
        raise RuntimeError(f"no path in {url}")
    return " ".join(paths)


def main() -> int:
    out = "app/src/main/res/drawable"
    for name, (symbol, filled) in ICONS.items():
        path = fetch(symbol, filled)
        with open(f"{out}/ic_{name}.xml", "w") as f:
            f.write(TEMPLATE.format(symbol=symbol + (" filled" if filled else ""), path=path))
        print("ok", name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
