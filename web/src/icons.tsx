export type IconName = keyof typeof ICONS;

/** Icon of a message channel (email, sms, chat, whatsapp, messenger, instagram, telegram, discord, push). */
export const channelIcon = (channel: string): IconName => (channel === 'call' ? 'phone' : channel === 'comment' ? 'quote' : ['email', 'sms', 'chat', 'whatsapp', 'messenger', 'instagram', 'telegram', 'discord', 'push'].includes(channel) ? (channel as IconName) : 'sms');

/**
 * Icon packs (Darstellung → Icon-Pack). Line, fine, bold, square and duotone are the same Lucide icons drawn
 * differently by CSS (theme.css: html[data-icons]); the hand-made "solid" set is loaded on demand
 * (theme/packs/solid.ts) and replaces the icons it has, the others keep their Lucide drawing.
 */
export type PackDef = Partial<Record<IconName, string>>;
const packs: Record<string, PackDef> = {};
let activePack = 'line';
/** Bumped when a pack's glyphs arrive, so icons already on screen redraw. */
let packVersion = 0;
const subscribers = new Set<() => void>();
const subscribe = (f: () => void) => (subscribers.add(f), () => void subscribers.delete(f));
export function setIconPack(id: string) {
  if (id === activePack) return;
  activePack = id;
  subscribers.forEach((f) => f());
}
export function registerIconPack(id: string, defs: PackDef) {
  packs[id] = defs;
  packVersion++;
  if (id === activePack) subscribers.forEach((f) => f());
}
const snapshot = () => `${activePack}:${packVersion}`;

export function Icon({ name, size = 16, ...rest }: { name: IconName } & Omit<LucideProps, 'ref'>) {
  useSyncExternalStore(subscribe, snapshot);
  const markup = packs[activePack]?.[name];
  if (markup) {
    const { className, style, color } = rest;
    // Static markup from our own pack file (theme/packs/*.ts), never user input.
    return <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width={size} height={size} fill="currentColor" aria-hidden="true" className={`ico ico-solid${className ? ` ${className}` : ''}`} style={color ? { ...style, color } : style} dangerouslySetInnerHTML={{ __html: markup }} />;
  }
  const C = ICONS[name];
  return <C size={size} strokeWidth={1.8} aria-hidden="true" className="ico" {...rest} />;
}
